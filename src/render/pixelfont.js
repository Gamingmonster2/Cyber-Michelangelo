export const GLYPH_W = 5;
export const GLYPH_H = 7;

const cache = new Map();

function glyph(ch) {
  const c = ch === '♥' || ch === '▶' || ch === '◀' || ch === '▲' || ch === '★' || ch === '✦' ? ch : ch.toUpperCase();
  if (cache.has(c)) return cache.get(c);
  const rows = G[c] || G['?'];
  const bits = rows.map((row) => row.split('').map((v) => v === '1'));
  cache.set(c, bits);
  return bits;
}

export function measureText(text, { scale = 1, spacing = 1 } = {}) {
  const chars = Array.from(String(text));
  if (!chars.length) return { w: 0, h: GLYPH_H * scale, chars: 0 };
  const advance = (GLYPH_W + spacing) * scale;
  return { w: advance * chars.length - spacing * scale, h: GLYPH_H * scale, chars: chars.length };
}

/**
 * Draw bitmap text.
 * opts: color (string or 7-row array), scale, spacing, align, alpha, shadow,
 *       outline, outlineColor, maxWidth (clips per glyph).
 */
export function drawText(ctx, text, x, y, opts = {}) {
  const {
    color = '#ffffff',
    scale = 1,
    spacing = 1,
    align = 'left',
    alpha = 1,
    shadow = null,
    outline = null,
    outlineColor = 'rgba(0,0,0,0.7)',
  } = opts;
  const chars = Array.from(String(text));
  const m = measureText(text, { scale, spacing });
  let startX = x;
  if (align === 'center') startX = x - m.w / 2;
  else if (align === 'right') startX = x - m.w;

  const prevAlpha = ctx.globalAlpha;
  if (alpha !== 1) ctx.globalAlpha = prevAlpha * alpha;

  const drawGlyphs = (offsetX, offsetY, fill, rowFill) => {
    ctx.fillStyle = fill;
    const advance = (GLYPH_W + spacing) * scale;
    let gx = Math.round(startX + offsetX);
    for (const ch of chars) {
      const bits = glyph(ch);
      for (let ry = 0; ry < GLYPH_H; ry++) {
        if (rowFill) ctx.fillStyle = rowFill[ry];
        for (let rx = 0; rx < GLYPH_W; rx++) {
          if (bits[ry][rx]) {
            ctx.fillRect(gx + rx * scale, Math.round(y + offsetY) + ry * scale, scale, scale);
          }
        }
      }
      gx += advance;
    }
  };

  if (shadow) {
    const s = typeof shadow === 'object' ? shadow : { x: scale, y: scale, color: shadow };
    drawGlyphs(s.x || 0, s.y || 0, s.color || 'rgba(0,0,0,0.55)');
  }
  if (outline) {
    const o = outlineColor;
    const d = Math.max(1, Math.floor(scale / 2));
    for (const [ox, oy] of [
      [-d, 0], [d, 0], [0, -d], [0, d],
      [-d, -d], [d, -d], [-d, d], [d, d],
    ]) {
      if (Array.isArray(color)) drawGlyphs(ox, oy, o);
      else drawGlyphs(ox, oy, o);
    }
  }
  if (Array.isArray(color)) {
    drawGlyphs(0, 0, color[0], color);
  } else {
    drawGlyphs(0, 0, color);
  }

  ctx.globalAlpha = prevAlpha;
  return m;
}

